import type { Scenario } from "@/lib/scenario/schema";
import type { Turn } from "@/lib/sim/types";
import type { CoachReport } from "./report";
import { scoreBand } from "./score";

/** Plain-text/markdown export of a report, for sharing or pasting into notes. */
export function reportToMarkdown(report: CoachReport, scenario: Scenario, turns: Turn[]): string {
  const lines: string[] = [];
  const band = scoreBand(report.overall);
  lines.push(`# ClientReady coaching report`);
  lines.push("");
  lines.push(`**Scenario:** ${scenario.title}  `);
  lines.push(`**Offer:** ${scenario.offer.name} (${scenario.offer.currency} ${scenario.offer.price})  `);
  lines.push(`**Client:** ${scenario.client.name}, ${scenario.client.role} (${scenario.client.country}, fictional)  `);
  lines.push(`**Overall:** ${report.overall ?? "n/a"}/100 (${band.label})  `);
  lines.push(`**Generated by:** ${report.generatedBy}${report.isDemo ? " (demo engine, not an LLM)" : ""}  `);
  lines.push(`**Date:** ${new Date(report.createdAt).toISOString().slice(0, 10)}`);
  lines.push("");
  lines.push(report.summary);
  lines.push("");
  lines.push(`## Scorecard`);
  for (const c of report.categories) {
    lines.push(`- **${c.name}** (weight ${c.weight}): ${c.score === null ? "not observed" : `${c.score}/100`}. ${c.rationale}`);
  }
  if (report.strengths.length) {
    lines.push("", `## What worked`);
    for (const s of report.strengths) lines.push(`- Turn ${s.turn}: "${s.quote}". ${s.why}`);
  }
  if (report.issues.length) {
    lines.push("", `## What to improve`);
    report.issues.forEach((i, n) => {
      lines.push("", `### ${n + 1}. ${i.title}`);
      if (i.quote) lines.push(`> "${i.quote}" (turn ${i.turn})`);
      lines.push(`- **Missing:** ${i.whatWasMissing}`);
      lines.push(`- **Why it mattered:** ${i.whyItMattered}`);
      lines.push(`- **Stronger answer:** "${i.betterResponse}"`);
      lines.push(`- **Why it works:** ${i.whyBetterWorks}`);
      if (i.principle) lines.push(`- **Principle:** ${i.principle.name} (${i.principle.source})`);
      lines.push(`- **Exercise:** ${i.exercise}`);
    });
  }
  if (report.plan.length) {
    lines.push("", `## Plan for next session`);
    report.plan.forEach((p, n) => lines.push(`${n + 1}. **${p.title}**: ${p.why} Exercise: ${p.exercise} Success: ${p.successMetric}`));
  }
  if (report.languageBridge.length) {
    lines.push("", `## Language bridge`);
    for (const b of report.languageBridge) lines.push(`- Turn ${b.turn}: "${b.original}" → "${b.clearerEnglish}". ${b.note}`);
  }
  lines.push("", `## Transcript`);
  for (const t of turns) {
    lines.push(`- [${t.index}] **${t.role === "client" ? scenario.client.name : "You"}**${t.source === "typed" ? " (typed)" : ""}: ${t.text}`);
    if (t.englishText) lines.push(`  - English rendering: ${t.englishText}`);
  }
  return lines.join("\n");
}
